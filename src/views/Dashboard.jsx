const calculateSystemScore = (stats) => {
  let score = 100;
  
  if (stats.cpu.percent > 80) score -= 20;
  else if (stats.cpu.percent > 60) score -= 10;
  
  if (stats.memory.percent > 85) score -= 25;
  else if (stats.memory.percent > 70) score -= 15;
  
  if (stats.disk.percent > 90) score -= 30;
  else if (stats.disk.percent > 80) score -= 20;
  
  if (stats.battery.percent < 20) score -= 15;
  
  return Math.max(0, Math.round(score));
};

const generateRecommendations = (stats) => {
  const recommendations = [];
  
  if (stats.cpu.percent > 80) {
    recommendations.push('High CPU usage detected. Consider closing unnecessary applications.');
  }
  
  if (stats.memory.percent > 85) {
    recommendations.push('Memory usage is critical. Close memory-intensive programs.');
  }
  
  if (stats.disk.percent > 90) {
    recommendations.push('Disk space is running low. Clean up temporary files.');
  }
  
  if (stats.battery.percent < 20) {
    recommendations.push('Battery is critically low. Connect to power source.');
  }
  
  if (recommendations.length === 0) {
    recommendations.push('System is running optimally. No action required.');
  }
  
  return recommendations;
};

const detectAnomalies = (stats, processes) => {
  const anomalies = [];
  
  const highCpuProcesses = processes.filter(p => p.cpu > 50);
  if (highCpuProcesses.length > 0) {
    anomalies.push({
      type: 'HIGH_CPU_PROCESS',
      message: `${highCpuProcesses.length} process(es) using >50% CPU`,
      details: highCpuProcesses.map(p => `${p.name} (${p.cpu}%)`)
    });
  }
  
  const highMemProcesses = processes.filter(p => p.memory > 20);
  if (highMemProcesses.length > 0) {
    anomalies.push({
      type: 'HIGH_MEMORY_PROCESS',
      message: `${highMemProcesses.length} process(es) using >20% memory`,
      details: highMemProcesses.map(p => `${p.name} (${p.memory}%)`)
    });
  }
  
  return anomalies;
};

